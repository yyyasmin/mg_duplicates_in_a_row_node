# Stub translation function
def translate(text):
    return f"ENGLISH: {text}" if text else ""

# Generate JSON files with desired structure
for i in range(0, len(pairs), 8):
    group = pairs[i:i+8]
    game_number = i // 8 + 1
    game_name = f"pesachQuestions_{game_number}"
    
    cards = []
    for j, (t1, t2) in enumerate(group):
        card_id = str(j + 1)
        name = f"p{card_id}"
        file_folder = f"../../assets/textures/{game_name}/png"
        file_name = f"{name}.png"
        file_full_path = f"{file_folder}/{file_name}"

        cards.append({
            "id": card_id,
            "name": name,
            "fileFolder": file_folder,
            "fileFullPath": file_full_path,
            "fileNameWithSufix": file_name,
            "background": "red",
            "text1": t1,
            "text2": t2,
            "text3": translate(t1),
            "text4": translate(t2),
            "faceType": "back"
        })

    final_data = {
        "gameName": game_name,
        "id": game_number,
        "gameCards": cards
    }

    filename = f"{game_name}.json"
    with open(filename, "w", encoding="utf-8") as f:
        json.dump(final_data, f, ensure_ascii=False, indent=2)

    print(f"Created: {filename}")
